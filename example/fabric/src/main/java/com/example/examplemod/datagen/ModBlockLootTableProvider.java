package com.example.examplemod.datagen;

import com.example.examplemod.block.ModBlocks;
import net.fabricmc.fabric.api.datagen.v1.FabricDataOutput;
import net.fabricmc.fabric.api.datagen.v1.provider.FabricBlockLootTableProvider;
import net.minecraft.core.HolderLookup;

import java.util.concurrent.CompletableFuture;

/// **Vanilla setup:** here we generate the loot table for the sapling, so it drops.
public class ModBlockLootTableProvider extends FabricBlockLootTableProvider {
    protected ModBlockLootTableProvider(FabricDataOutput dataOutput, CompletableFuture<HolderLookup.Provider> registryLookup) {
        super(dataOutput, registryLookup);
    }

    @Override
    public void generate() {
        dropSelf(ModBlocks.SIMPLE_EXAMPLE_SAPLING);
        dropSelf(ModBlocks.FANCY_EXAMPLE_SAPLING);
    }
}
